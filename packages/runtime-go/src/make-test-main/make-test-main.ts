import type { GoPackage } from '../domain/go-package.domain-model.ts'

export const xtestImportPath = (pkg: GoPackage) => `${pkg.importPath}_test`

const entry = (alias: string, name: string) => `\t{${JSON.stringify(name)}, ${alias}.${name}},`

export const makeTestMain = (pkg: GoPackage): string => {
  const hasXtest = pkg.xtestGoFiles.length > 0
  const needTest = pkg.tests.length > 0 || pkg.testMain === 'test'
  const needXtest = pkg.xtests.length > 0 || pkg.testMain === 'xtest'
  const imports = [
    '"io"',
    '"os"',
    '"reflect"',
    '"strings"',
    '"testing"',
    '"time"',
    `${needTest ? '_test' : '_'} ${JSON.stringify(pkg.importPath)}`,
    ...(hasXtest ? [`${needXtest ? '_xtest' : '_'} ${JSON.stringify(xtestImportPath(pkg))}`] : []),
  ]
  const run =
    pkg.testMain === undefined
      ? '\tos.Exit(m.Run())'
      : [
          `\t${pkg.testMain === 'test' ? '_test' : '_xtest'}.TestMain(m)`,
          '\tos.Exit(int(reflect.ValueOf(m).Elem().FieldByName("exitCode").Int()))',
        ].join('\n')

  return `// Code generated by Typika. DO NOT EDIT.

package main

import (
${imports.map((line) => `\t${line}`).join('\n')}
)

var tests = []testing.InternalTest{
${[...pkg.tests.map((test) => entry('_test', test.name)), ...pkg.xtests.map((test) => entry('_xtest', test.name))].join('\n')}
}

type corpusEntry = struct {
\tParent     string
\tPath       string
\tData       []byte
\tValues     []any
\tGeneration int
\tIsSeed     bool
}

type testDeps struct{}

func (testDeps) ImportPath() string { return ${JSON.stringify(pkg.importPath)} }
func (testDeps) MatchString(pattern, name string) (bool, error) { return strings.Contains(name, pattern), nil }
func (testDeps) SetPanicOnExit0(bool) {}
func (testDeps) StartCPUProfile(io.Writer) error { return nil }
func (testDeps) StopCPUProfile() {}
func (testDeps) StartTestLog(io.Writer) {}
func (testDeps) StopTestLog() error { return nil }
func (testDeps) WriteProfileTo(string, io.Writer, int) error { return nil }
func (testDeps) CoordinateFuzzing(time.Duration, int64, time.Duration, int64, int, []corpusEntry, []reflect.Type, string, string) error {
\treturn nil
}
func (testDeps) RunFuzzWorker(func(corpusEntry) error) error { return nil }
func (testDeps) ReadCorpus(string, []reflect.Type) ([]corpusEntry, error) { return nil, nil }
func (testDeps) CheckCorpus([]any, []reflect.Type) error { return nil }
func (testDeps) ResetCoverage() {}
func (testDeps) SnapshotCoverage() {}
func (testDeps) InitRuntimeCoverage() (string, func(string, string) (string, error), func() float64) {
\treturn "", nil, nil
}

func main() {
\tm := testing.MainStart(testDeps{}, tests, nil, nil, nil)
${run}
}
`
}
